test('minor simulated guardian link verifies declaration but still requires operator relationship review',async({page,browser})=>{
  await page.goto('http://127.0.0.1:4273/');await page.getByRole('button',{name:'Create an account',exact:true}).click();
  await page.getByRole('button',{name:'Yes, under 18',exact:true}).click();
  await page.getByLabel('Student display name',{exact:true}).fill('Fictional minor');
  await page.getByLabel('Guardian email',{exact:true}).fill(`minor-${Date.now()}@fictional.invalid`);
  await page.getByLabel('Password',{exact:true}).fill('fictional-onboarding-password');await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Create account',exact:true}).click();await page.getByRole('button',{name:'Set up my learning preferences',exact:true}).click();
  await page.getByLabel('Authorize essential account and learning processing').check();
  await page.getByLabel('Guardian email',{exact:true}).fill('simulated-guardian@fictional.invalid');
  await page.getByRole('button',{name:'Create fictional guardian review request'}).click();
  const href=await page.getByRole('link',{name:'Open simulated guardian link'}).getAttribute('href');
  const context=await browser.newContext();
  try {
    const guardian=await context.newPage();await guardian.goto(href!);
    await expect(guardian.getByText(/Optional personalization: declined/)).toBeVisible();
    await guardian.getByRole('checkbox').check();await guardian.getByRole('button',{name:'Verify simulated token and declaration'}).click();
    await expect(guardian.getByRole('status')).toContainText('Independent relationship review');
    await page.getByRole('button',{name:'Check authorization status'}).click();await expect(page.getByText(/Guardian review: verified/)).toBeVisible();
    await expect(page.getByLabel('What should Coteacher call you?',{exact:true})).toHaveCount(0);
    await guardian.goto(href!);await expect(guardian.getByRole('status')).toContainText('already used');
    await guardian.goto('http://127.0.0.1:4275/');await guardian.getByLabel('Email or school-issued username').fill('reviewer@fictional.invalid');
    await guardian.getByLabel('Password',{exact:true}).fill('fictional-reviewer-password');await guardian.getByRole('button',{name:'Sign in',exact:true}).click();
    await guardian.getByRole('navigation',{name:'School navigation'}).getByRole('button',{name:'Settings',exact:true}).click();
    const review=guardian.getByRole('article').filter({hasText:'simulated-guardian@fictional.invalid'});
    await review.getByLabel('Relationship decision').selectOption('approve');await review.getByLabel('Independent review reason').fill('Fictional operator verified guardian relationship');
    await review.getByRole('button',{name:'Save guardian review'}).click();await expect(review).toContainText('approved');
    await page.getByRole('button',{name:'Check authorization status'}).click();await expect(page.getByText(/Optional personalization is off/)).toBeVisible();
    await page.getByRole('button',{name:'Continue with basic learning'}).click();await page.getByRole('button',{name:'Back to learning',exact:true}).click();
    await expect(page.getByRole('button',{name:'Refresh lessons',exact:true})).toBeVisible();
  } finally { await context.close(); }
});
