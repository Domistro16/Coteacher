import { expect, test } from '@playwright/test';
import { teacherSources } from './teacher-navigation';
import { assertWatermark } from './motion-assertions';

test('studio and projector share five-second instructional motion, transitions and reduced-motion alternatives', async ({ page, context }, info) => {
  test.setTimeout(60000); await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('http://127.0.0.1:4274'); await teacherSources(page);
  await page.getByRole('button', { name: 'Use reviewed demo materials' }).click();
  await page.getByRole('button', { name: 'Generate simulated lesson' }).click();
  await page.getByRole('checkbox').check(); await page.getByRole('button', { name: 'Approve lesson', exact: true }).click();
  await page.getByRole('button', { name: 'Teach / projector' }).click(); await page.getByRole('button', { name: 'Start presentation' }).click();
  const studio = page.locator('.studio-canvas-space'), svg = studio.locator('svg');
  await expect(svg).toHaveAttribute('data-motion-loop-ms', '5000'); await assertWatermark(studio);
  const opening = page.waitForEvent('popup'); await page.getByRole('button', { name: 'Open projector display' }).click();
  const projector = await opening; await projector.emulateMedia({ reducedMotion: 'no-preference' });
  const projected = projector.locator('.teaching-canvas'), projection = projected.locator('svg');
  await expect(projector.locator('.classroom-projector')).toHaveAttribute('data-presentation-step-id', 'step-light');
  await assertWatermark(projected);
  const initial = Number(await svg.getAttribute('data-motion-time-ms'));
  await expect.poll(async () => Number(await svg.getAttribute('data-motion-time-ms')), { timeout: 9000 }).toBeGreaterThan(initial + 5000);
  const times = await Promise.all([svg.getAttribute('data-motion-time-ms'), projection.getAttribute('data-motion-time-ms')]);
  expect(Math.abs(Number(times[0]) - Number(times[1]))).toBeLessThan(250);
  expect(Number(await svg.getAttribute('data-motion-phase'))).toBeCloseTo((Number(times[0]) % 5000) / 5000, 1);
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Next visual' }).click();
  await expect(projector.locator('.classroom-projector')).toHaveAttribute('data-presentation-step-id', 'step-refraction');
  await expect(svg.locator('[data-build=ray]')).toHaveAttribute('d', 'M130 183L210 110L353 37');
  expect(Number(await svg.locator('[data-build=ray]').getAttribute('data-build-progress'))).toBeLessThan(.5);
  await projector.screenshot({ path: info.outputPath('projector-refraction-building.png') });
  await expect.poll(async () => Number(await svg.locator('[data-build=ray]').getAttribute('data-build-progress'))).toBeGreaterThan(.95);
  await expect.poll(async () => Number(await svg.locator('[data-build=label]').last().getAttribute('data-build-progress'))).toBe(1);
  expect(await svg.evaluate(element => getComputedStyle(element).animationName)).toBe('lesson-visual-enter');
  await projector.screenshot({ path: info.outputPath('animated-projector.png') });
  await page.emulateMedia({ reducedMotion: 'reduce' }); await projector.emulateMedia({ reducedMotion: 'reduce' });
  await expect(svg).toHaveAttribute('data-reduced-motion', 'true');
  await expect(projection).toHaveAttribute('data-reduced-motion', 'true');
  await expect(svg).toHaveAttribute('data-motion-phase', '0.00000');
  await expect(svg.locator('[data-build=ray]')).toHaveAttribute('data-build-progress', '1.0000');
  for (const label of await projection.locator('[data-build=label]').all()) await expect(label).toHaveAttribute('data-build-progress', '1.0000');
  expect(await projection.evaluate(element => getComputedStyle(element).animationName)).toBe('none');
  await assertWatermark(studio); await assertWatermark(projected);
  await page.getByRole('button', { name: 'Previous visual' }).click();
  await expect(projector.locator('.classroom-projector')).toHaveAttribute('data-presentation-step-id', 'step-light');
  await expect(projection).toHaveAttribute('data-motion-phase', '0.00000');
  await projector.close();
});
