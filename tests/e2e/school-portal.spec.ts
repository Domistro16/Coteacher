import { test, expect } from '@playwright/test';

test('school owner registers, persists a pending school and cannot invite before review', async ({ page }) => {
  await page.goto('http://127.0.0.1:4275/');
  await expect(page.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  await page.getByLabel('Your name', { exact: true }).fill('Fictional school owner');
  await page.getByLabel('Email or school-issued username').fill(`school-${Date.now()}@fictional.invalid`);
  await page.getByLabel('Password').fill('fictional-school-password');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Register a school' })).toBeVisible();
  await page.getByLabel('School name', { exact: true }).fill('Fictional School of Curiosity');
  await page.getByLabel('Location', { exact: true }).fill('Fictional location');
  await page.getByLabel('School contact').fill('office@fictional.invalid');
  await page.getByLabel('Verification evidence / reference').fill('Simulated reference only');
  await page.getByLabel('Classes offered').selectOption('Primary through JSS');
  await page.getByRole('button', { name: 'Submit for platform review' }).click();
  await expect(page.getByText(/School ID:/)).toContainText('pending');
  await expect(page.getByRole('button', { name: 'Create invitation' })).toHaveCount(0);
  await page.reload();
  await expect(page.getByText(/School ID:/)).toContainText('pending');
  await expect(page.locator('.school-stats article').filter({has:page.getByText('Teachers',{exact:true})}).locator('strong')).toHaveText('0');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 360, height: 800 });
  await page.screenshot({ path: 'test-results/school-portal-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1366, height: 900 });
  await page.screenshot({ path: 'test-results/school-portal-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible();
  await page.getByLabel('Email or school-issued username').fill('reviewer@fictional.invalid');
  await page.getByLabel('Password').fill('fictional-reviewer-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  const review = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Fictional School of Curiosity' }) });
  await review.getByLabel('Decision').selectOption('active');
  await review.getByLabel('Review reason').fill('Fictional school reviewed for browser test');
  await review.getByRole('button', { name: 'Save review' }).click();
  await expect(page.getByText(/School ID:/)).toContainText('active');
});
